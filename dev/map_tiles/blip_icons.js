// GTA's blip icons for the pause menu map, from FiveM's docs (https://docs.fivem.net/docs/game-references/blips/).
//
//   node dev/map_tiles/blip_icons.js <folder>
//
// <folder> holds list.txt ("<sprite id> <name> <png|gif>" per line, parsed from that page) and the
// downloaded <name>.png / <name>.gif files. Writes:
//   whip_assets/img/blips/<sprite id>.webp   (at most 64 px; an animated GIF keeps its first frame)
//   whip_core/html/js/blip-names.js          (sprite id -> a readable name, for the map's legend)
// Headless Chrome does the decoding and encoding. The icons are Rockstar's.
const { spawn } = require('child_process');
const fs = require('fs');
const path = require('path');

const CHROME = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const SRC = path.resolve(process.argv[2] || '');
const OUT = require('../assets_dirs.js').assetDir('img/blips');   // in its whip_assets_N
const NAMES = path.resolve(__dirname, '..', '..', 'html', 'js', 'blip-names.js');
const PORT = 9333 + Math.floor(Math.random() * 400);
const profile = path.join(require('os').tmpdir(), 'whip-blip-icons-' + PORT);
const fileUrl = (p) => 'file:///' + p.replace(/\\/g, '/');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const listFile = path.join(SRC, 'list.txt');
if (!fs.existsSync(listFile)) { console.error('usage: node dev/map_tiles/blip_icons.js <folder with list.txt>'); process.exit(1); }
const list = fs.readFileSync(listFile, 'utf8').trim().split(/\r?\n/).map((l) => l.split(' '))
    .filter((p) => p.length === 3).map(([id, name, ext]) => ({ id: Number(id), name, ext }));

/** radar_gang_attack_package -> "Gang attack package". */
const readable = (name) => {
    const s = name.replace(/^radar_/, '').replace(/_/g, ' ').trim();
    return s.charAt(0).toUpperCase() + s.slice(1);
};

(async () => {
    const chrome = spawn(CHROME, [
        '--headless=new', '--disable-gpu', '--allow-file-access-from-files', '--no-first-run',
        '--remote-debugging-port=' + PORT, '--user-data-dir=' + profile, 'about:blank',
    ], { stdio: 'ignore' });
    let pageWs;
    for (let i = 0; i < 60 && !pageWs; i++) {
        await sleep(250);
        try {
            const tabs = await (await fetch('http://127.0.0.1:' + PORT + '/json/list')).json();
            const page = tabs.find((t) => t.type === 'page');
            if (page) pageWs = page.webSocketDebuggerUrl;
        } catch (_) { /* not up yet */ }
    }
    if (!pageWs) { console.error('chrome did not start'); chrome.kill(); process.exit(1); }
    const ws = new WebSocket(pageWs);
    await new Promise((res, rej) => { ws.onopen = res; ws.onerror = rej; });
    let mid = 0;
    const pending = new Map();
    ws.onmessage = (ev) => {
        const m = JSON.parse(ev.data);
        if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); }
    };
    const send = (method, params) => new Promise((res) => {
        const n = ++mid; pending.set(n, res);
        ws.send(JSON.stringify({ id: n, method, params: params || {} }));
    });
    await send('Runtime.enable');
    // A file:// page first: about:blank may not read local files, and a canvas they tainted will
    // not hand back its pixels.
    await send('Page.navigate', { url: fileUrl(path.join(__dirname, 'bake.html')) });
    await sleep(1000);
    // One converter, defined into that page: load, scale to <= 64 px, WebP.
    await send('Runtime.evaluate', { expression: `window.conv = (url) => new Promise((ok, bad) => {
        const i = new Image();
        i.onload = () => { const k = Math.min(1, 64 / Math.max(i.width, i.height));
            const c = document.createElement('canvas'); c.width = Math.round(i.width * k); c.height = Math.round(i.height * k);
            c.getContext('2d').drawImage(i, 0, 0, c.width, c.height); ok(c.toDataURL('image/webp', 0.92)); };
        i.onerror = () => bad(new Error('load ' + url)); i.src = url; })` });

    fs.mkdirSync(OUT, { recursive: true });
    const names = {};
    let done = 0;
    for (const b of list) {
        const src = path.join(SRC, b.name + '.' + b.ext);
        if (!fs.existsSync(src)) continue;
        const r = await send('Runtime.evaluate', { expression: 'conv(' + JSON.stringify(fileUrl(src)) + ')', awaitPromise: true, returnByValue: true });
        const url = r.result && r.result.result && r.result.result.value;
        if (typeof url !== 'string' || !url.startsWith('data:image/webp;base64,')) { console.error('failed: ' + src); continue; }
        fs.writeFileSync(path.join(OUT, b.id + '.webp'), Buffer.from(url.slice(23), 'base64'));
        names[b.id] = readable(b.name);
        done++;
    }

    fs.writeFileSync(NAMES, '// GTA blip sprite id -> a readable name, for the pause map\'s legend when a blip has no name of\n'
        + '// its own. Generated by dev/map_tiles/blip_icons.js from FiveM\'s blip list; the icons are\n'
        + '// whip_assets/img/blips/<id>.webp. Do not edit by hand.\n'
        + 'export const BLIP_NAMES = ' + JSON.stringify(names) + ';\n');
    console.log('converted ' + done + ' icons -> ' + OUT + '\nnames -> ' + NAMES);

    ws.close();
    chrome.kill();
    await sleep(500);
    try { fs.rmSync(profile, { recursive: true, force: true }); } catch (_) { /* Chrome may still hold it */ }
})().catch((e) => { console.error(e); process.exit(1); });
