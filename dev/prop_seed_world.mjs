#!/usr/bin/env node
// ============================================
// prop_seed_world — every other prop in the game, placeable
// ============================================
//
// Josh, 28 Oct 2026: every prop in the game becomes placeable furniture. 3D Clanker's icon job lists
// them (about 16,500 in GTA V Enhanced) with a category each; this turns that list into
// server/prop_catalog_seed_world.lua, which adds them to PropCatalogSeed after the hand-picked
// server/prop_catalog_seed.lua. prop_catalog.lua seeds the table from both as it always has: only
// models the table has never had.
//
//   node dev/prop_seed_world.mjs <list.csv>                 writes server/prop_catalog_seed_world.lua
//   node dev/prop_seed_world.mjs <list.csv> --out <file>    a trial run, written there instead
//
// The CSV has a header naming at least model, category and name (any order; a field may be quoted).
// Each row:
//   - model     the archetype name, lowercase (letters, digits, _), at most 80
//   - category  a key in config.lua's Config.PropCategories ('hidden': left out, never shipped)
//   - name      what the furnisher shows, at most 64 (empty: the furnisher makes one from the model)
// Rows the hand-picked seed already has are left out: its line, its name and its category win.
// A row that breaks a rule is left out and listed, never guessed at.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const CORE = path.resolve(HERE, '..');
const args = process.argv.slice(2);
const outAt = args.indexOf('--out');   // --out <file>: somewhere else (a trial run)
const OUT = outAt >= 0 ? path.resolve(args[outAt + 1]) : path.join(CORE, 'server', 'prop_catalog_seed_world.lua');
if (outAt >= 0) args.splice(outAt, 2);

const file = args[0];
if (!file) {
    console.error('usage: node dev/prop_seed_world.mjs <list.csv> [--out <file>]');
    process.exit(1);
}

/** One CSV line into fields: commas, and double-quoted fields with "" for a quote. */
function fields(line) {
    const out = [];
    let cur = '', quoted = false;
    for (let i = 0; i < line.length; i++) {
        const ch = line[i];
        if (quoted) {
            if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++; }
            else if (ch === '"') quoted = false;
            else cur += ch;
        } else if (ch === '"') quoted = true;
        else if (ch === ',') { out.push(cur); cur = ''; }
        else cur += ch;
    }
    out.push(cur);
    return out.map((f) => f.trim());
}

/** The keys config.lua files props under. */
function categories() {
    const cfg = fs.readFileSync(path.join(CORE, 'config.lua'), 'utf8');
    const from = cfg.indexOf('Config.PropCategories = {');
    const to = cfg.indexOf('\n}', from);
    return new Set([...cfg.slice(from, to).matchAll(/key = '([a-z0-9_]+)'/g)].map((m) => m[1]));
}

/** The models the hand-picked seed has. */
function handPicked() {
    const src = fs.readFileSync(path.join(CORE, 'server', 'prop_catalog_seed.lua'), 'utf8');
    return new Set([...src.matchAll(/^\s*\{\s*'([^']+)'/gm)].map((m) => m[1].toLowerCase()));
}

const luaString = (s) => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";

const lines = fs.readFileSync(file, 'utf8').replace(/^﻿/, '').split(/\r?\n/).filter((l) => l.trim() !== '');
const head = fields(lines[0]).map((h) => h.toLowerCase());
const col = { model: head.indexOf('model'), category: head.indexOf('category'), name: head.indexOf('name') };
if (col.model < 0 || col.category < 0 || col.name < 0) {
    console.error('the header must name model, category and name; it has: ' + head.join(', '));
    process.exit(1);
}

const cats = categories();
const known = handPicked();
const seen = new Set();
const rows = [];
const skipped = { hidden: 0, handPicked: 0, duplicate: 0 };
const bad = [];
for (let i = 1; i < lines.length; i++) {
    const f = fields(lines[i]);
    const model = (f[col.model] || '').toLowerCase();
    const category = (f[col.category] || '').toLowerCase();
    const name = (f[col.name] || '').replace(/[\x00-\x1f]/g, ' ').slice(0, 64);
    if (category === 'hidden') { skipped.hidden++; continue; }
    if (!/^[a-z0-9_]{1,80}$/.test(model) || /^\d+$/.test(model)) { bad.push(`line ${i + 1}: model "${model}"`); continue; }
    if (!cats.has(category)) { bad.push(`line ${i + 1}: ${model}: category "${category}" is not in Config.PropCategories`); continue; }
    if (known.has(model)) { skipped.handPicked++; continue; }
    if (seen.has(model)) { skipped.duplicate++; continue; }
    seen.add(model);
    rows.push([model, category, name]);
}
rows.sort((a, b) => (a[1] === b[1] ? (a[0] < b[0] ? -1 : 1) : (a[1] < b[1] ? -1 : 1)));

const perCat = {};
for (const r of rows) perCat[r[1]] = (perCat[r[1]] || 0) + 1;

const out = [
    '-- GENERATED by dev/prop_seed_world.mjs from ' + path.basename(file) + ': every other prop in the game, placeable',
    '-- (Josh, 28 Oct 2026). Do not edit by hand: run the script again on a new list.',
    '--',
    '-- Each line is { model, category, name }, as in server/prop_catalog_seed.lua, which loads first and wins: a model',
    '-- it has is left out here. prop_catalog.lua seeds the table from both, only with models the table has never had,',
    '-- so a prop an admin removed or moved stays as they left it.',
    '',
    'local world = {',
    ...rows.map((r) => `    { ${luaString(r[0])}, ${luaString(r[1])}, ${luaString(r[2])} },`),
    '}',
    '',
    'for i = 1, #world do PropCatalogSeed[#PropCatalogSeed + 1] = world[i] end',
    '',
];
fs.writeFileSync(OUT, out.join('\n'));

console.log(`wrote ${path.relative(CORE, OUT)}: ${rows.length} props`);
console.log('  per category: ' + Object.entries(perCat).sort().map(([k, v]) => `${k} ${v}`).join(', '));
console.log(`  left out: ${skipped.handPicked} already hand-picked, ${skipped.hidden} hidden, ${skipped.duplicate} listed twice, ${bad.length} broke a rule`);
for (const b of bad.slice(0, 40)) console.log('    ' + b);
if (bad.length > 40) console.log(`    ... and ${bad.length - 40} more`);
